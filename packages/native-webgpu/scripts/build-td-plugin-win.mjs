// Windows x64 counterpart of build-td-plugin.mjs (invoked by it on Windows):
//   node scripts/build-td-plugin.mjs [--chop]
// Produces ONE self-contained DLL per operator. Its Resources (renderer/chop JS,
// fonts, DeclaredParameters.py) are packed into an "AVR1" blob embedded as RCDATA;
// native/embedded/Platform.h extracts it once per content hash at load time.
// Output: prebuilt/windows-x64/<Name>-<tag>.dll and current[-chop].txt, then the
// distribution ZIP is refreshed (as on macOS) once both operators exist.
import {build} from 'esbuild';
import {seedrandomNotices} from './seedrandom-notices.mjs';
import {execFileSync} from 'node:child_process';
import {mkdirSync, writeFileSync, readFileSync, readdirSync, existsSync, copyFileSync, realpathSync, statSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve, relative} from 'node:path';
import {createHash} from 'node:crypto';

const root = fileURLToPath(new URL('../', import.meta.url));
const repo = resolve(root, '../..');
const chop = process.argv.includes('--chop');
const name = chop ? 'AvToolsChannels' : 'AvToolsSketch';
const jobs = process.env.AVTOOLS_BUILD_JOBS ?? '3';

// 1. Script host bundle (identical to macOS).
const renderer = await build({absWorkingDir: root, entryPoints: [resolve(root, chop ? 'src/td-chop-runtime.ts' : 'src/td-runtime.ts')], write: false, bundle: true, platform: 'neutral', format: 'iife', target: 'es2022', nodePaths: [resolve(root, 'node_modules')]});

// 2. Resources tree, same names the native code reads on macOS.
const files = new Map();  // relative path -> Buffer
files.set('DeclaredParameters.py', readFileSync(resolve(root, 'native/td/DeclaredParameters.py')));
files.set('native-build.txt', Buffer.from('embedded-static\n'));
files.set(chop ? 'chop.js' : 'renderer.js', Buffer.from(renderer.outputFiles[0].contents));
if (!chop) {
  const fonts = existsSync(resolve(root, 'dist/fonts')) ? resolve(root, 'dist/fonts') : resolve(repo, 'apps/deno-notebooks/assets/fonts');
  for (const font of readdirSync(fonts).sort()) if (statSync(resolve(fonts, font)).isFile()) files.set('fonts/' + font, readFileSync(resolve(fonts, font)));
}

// 3. Pack: "AVR1", u32 count, then per entry u32 len, UTF-8 path, u64 size, bytes.
const parts = [Buffer.from('AVR1'), u32(files.size)];
for (const [path, bytes] of [...files].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
  const encoded = Buffer.from(path, 'utf8');
  parts.push(u32(encoded.length), encoded, u64(bytes.length), bytes);
}
const blob = Buffer.concat(parts);
const blobHash = createHash('sha256').update(blob).digest('hex');
function u32(n) { const b = Buffer.alloc(4); b.writeUInt32LE(n); return b; }
function u64(n) { const b = Buffer.alloc(8); b.writeBigUInt64LE(BigInt(n)); return b; }

// 4. Stage runtime sources, configure, then write the resource script the GN
// target compiles. The hash comment changes the .rc whenever the blob changes.
execFileSync(process.execPath, [resolve(root, 'scripts/embedding-win.mjs'), 'stage', '--jobs', jobs], {stdio: 'inherit'});
const dawn = realpathSync(resolve(root, 'upstream/node-webgpu/third_party/dawn'));
const generated = resolve(dawn, 'avtools/embedded/generated'); mkdirSync(generated, {recursive: true});
writeFileSync(resolve(generated, `${name}.avr`), blob);
writeFileSync(resolve(generated, `${name}.hash`), blobHash);
writeFileSync(resolve(generated, `${name}.rc`), `// Generated by build-td-plugin-win.mjs; resources sha256 ${blobHash}\n101 RCDATA "${name}.avr"\n102 RCDATA "${name}.hash"\n`);

// 5. Link the operator DLL.
const out = resolve(dawn, 'out/avtools-win');
// Same toolchain environment as embedding-win.mjs: ninja may re-run GN, whose
// Windows toolchain detection needs the local VS install (not Google's toolchain).
const vs = process.env.vs2026_install ?? 'C:\\Program Files (x86)\\Microsoft Visual Studio\\18\\BuildTools';
const toolchainEnv = {...process.env, DEPOT_TOOLS_WIN_TOOLCHAIN: '0', DEPOT_TOOLS_UPDATE: '0', vs2026_install: vs,
  PATH: realpathSync(resolve(dawn, '../depot_tools')) + ';' + process.env.PATH};
execFileSync(resolve(dawn, 'third_party/ninja/ninja.exe'), ['-C', out, '-j', jobs, `avtools/embedded:${name}`], {cwd: dawn, stdio: 'inherit', env: toolchainEnv});
const dll = resolve(out, `${name}.dll`);

// 6. Publish a versioned copy; never overwrite a DLL that TD may have loaded.
const tag = createHash('sha256').update(readFileSync(dll)).digest('hex').slice(0, 12);
const prebuilt = resolve(root, 'prebuilt/windows-x64'); mkdirSync(prebuilt, {recursive: true});
const published = resolve(prebuilt, `${name}-${tag}.dll`);
if (!existsSync(published)) copyFileSync(dll, published);
// Notices the distribution ships beside the DLLs (not needed at runtime).
const notices = resolve(prebuilt, 'notices'); mkdirSync(notices, {recursive: true});
copyFileSync(resolve(dawn, 'third_party/v8/src/LICENSE'), resolve(notices, 'V8-LICENSE.txt'));
// Dawn, its third_party and Rust crate notices (Windows crate graph), as on macOS.
execFileSync(process.execPath, [resolve(root, 'scripts/notices.mjs')], {stdio: 'inherit'});
copyFileSync(resolve(root, 'dist/THIRD_PARTY_NOTICES.txt'), resolve(notices, 'THIRD_PARTY_NOTICES.txt'));
const libuv = JSON.parse(readFileSync(resolve(root, 'native-manifest.json'), 'utf8')).libuv.version;
copyFileSync(resolve(root, `build/libuv-win/libuv-v${libuv}/LICENSE`), resolve(notices, 'libuv-LICENSE.txt'));
writeFileSync(resolve(notices, 'seedrandom-LICENSE.txt'), seedrandomNotices(root));
if (!chop) for (const [path, bytes] of files) if (/LICENSE/i.test(path)) writeFileSync(resolve(notices, path.replace('fonts/', 'font-')), bytes);
writeFileSync(resolve(prebuilt, chop ? 'current-chop.txt' : 'current.txt'), `${name}-${tag}.dll\n`);
console.log(`${relative(repo, published)} (resources ${(blob.length / 1048576).toFixed(1)} MiB, sha256 ${blobHash.slice(0, 16)})`);
if (existsSync(resolve(prebuilt, 'current.txt')) && existsSync(resolve(prebuilt, 'current-chop.txt')))
  execFileSync(process.execPath, [resolve(root, 'scripts/package-td.mjs')], {stdio: 'inherit'});
