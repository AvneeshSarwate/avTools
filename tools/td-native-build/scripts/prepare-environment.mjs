// Deterministic TD profile derived from emitted first-party and pinned upstream types.
import {readFileSync,writeFileSync,mkdirSync,cpSync} from 'node:fs';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';
const repo=resolve(import.meta.dirname,'../../..');
const native=resolve(repo,'packages/native-webgpu');
const dest=resolve(native,'td-types');mkdirSync(dest,{recursive:true});
const emitted=resolve(native,'dist/types');
cpSync(resolve(emitted,'packages/core-timing'),resolve(dest,'timing'),{recursive:true});
cpSync(resolve(emitted,'apps/deno-notebooks/tools/p5gpu_text'),resolve(dest,'p5gpu_text'),{recursive:true});
let p5=readFileSync(resolve(emitted,'apps/deno-notebooks/tools/p5gpu_renderer.d.ts'),'utf8');
assert.equal((p5.match(/string \| URL/g)||[]).length,2,'Audit changed P5 platform signatures');
p5=p5.replaceAll('string | URL','string').replace('export declare class P5GPU {','declare class TDRenderer {');
assert.ok(p5.includes('declare class TDRenderer {'));
p5+='\n/** Instance supplied by the TOP; no public native renderer constructor. */\nexport type P5GPU = TDRenderer;\n';
writeFileSync(resolve(dest,'p5.d.ts'),'// Generated by prepare-environment.mjs from the portable renderer declarations.\n'+p5);
const upstream=resolve(native,'node_modules/@webgpu/types');
assert.equal(JSON.parse(readFileSync(resolve(upstream,'package.json'))).version,'0.1.72','Review TD adapter for an upstream update');
cpSync(resolve(upstream,'LICENSE'),resolve(dest,'WEBGPU-LICENSE'));
let gpu=readFileSync(resolve(upstream,'dist/index.d.ts'),'utf8');
function patch(pattern,replacement,count=1){let n=0;gpu=gpu.replace(pattern,(...args)=>{n++;return typeof replacement==='function'?replacement(...args):replacement});assert.equal(n,count,String(pattern));}
patch(/\/\/ Stronger typing for getContext\(\)[\s\S]*?interface HTMLVideoElement \{\}/,'// Browser canvas/video objects are not part of the TD host.');
patch(/type GPUCopyExternalImageSource =[\s\S]*?;/,'type GPUCopyExternalImageSource = never;');
patch(/source:\s*\| HTMLVideoElement\s*\| VideoFrame;/,'source: never;');
patch(/readonly canvas:\s*\| HTMLCanvasElement\s*\| OffscreenCanvas;/,'readonly canvas: never;');
// Dawn exposes these objects but they have illegal constructors, even with arguments.
for(const name of ['GPUValidationError','GPUOutOfMemoryError','GPUInternalError']) {
 patch(new RegExp('declare var '+name+': \\{[\\s\\S]*?\\n\\};'),'declare var '+name+': { prototype: '+name+'; };');
}
const constructors=[];
patch(/declare var (\w+): \{[^}]*\};/g,(block,name)=>{constructors.push(block.replace(/\s*new \(\): never;/,''));return '';},34);
patch(/declare var (\w+): (\w+);/g,(block)=>{constructors.push(block);return '';},5);
// Value declarations live only in the TOP profile; interface names do not imply constructors.
writeFileSync(resolve(dest,'webgpu.d.ts'),'// Derived from @webgpu/types 0.1.72; see WEBGPU-LICENSE. Generated; do not edit.\n'+'type BufferSource = ArrayBufferView | ArrayBuffer;\ntype PredefinedColorSpace = "srgb" | "display-p3";\n'+gpu);
writeFileSync(resolve(native,'td-top-runtime.d.ts'),'/// <reference path="./td-runtime.d.ts" />\n/// <reference path="./td-types/webgpu.d.ts" />\n/** TOP-only Dawn globals. Mixed projects opt into this union profile. */\n'+constructors.join('\n')+'\n');
